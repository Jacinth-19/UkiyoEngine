#!/usr/bin/env python3
"""True blue-noise dither tile by the void-and-cluster method (Ulichney, 1993).

Writes src/engine/blue_noise_64.h (a 64x64 uint8 tile, every value 0..255 used once for each rank
class) and renders/blue_noise_64.png for inspection. Deterministic: the same seed gives the same tile.

Method: a binary pattern at 10% density is relaxed by swapping the tightest cluster with the biggest
void until stable (phase 1). Ranks are then assigned: ones are removed from the tightest cluster
(phase 2), and zeros are filled into the biggest void (phase 3). The rank is the texel value.
"""
import os
import numpy as np
from PIL import Image

SIZE = 64
SIGMA = 1.5
SEED = 1
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def gaussian_freq_kernel(n, sigma):
    # Toroidal Gaussian in the frequency domain, so the filter wraps like the tile does.
    fy = np.fft.fftfreq(n)[:, None]
    fx = np.fft.fftfreq(n)[None, :]
    return np.exp(-2.0 * (np.pi * sigma) ** 2 * (fx * fx + fy * fy))


G = gaussian_freq_kernel(SIZE, SIGMA)


def energy(pattern):
    return np.real(np.fft.ifft2(np.fft.fft2(pattern.astype(np.float64)) * G))


def tightest_one(pat):
    e = energy(pat)
    e[pat == 0] = -np.inf
    return np.unravel_index(np.argmax(e), pat.shape)


def biggest_void(pat):
    e = energy(pat)
    e[pat == 1] = np.inf
    return np.unravel_index(np.argmin(e), pat.shape)


def generate():
    rng = np.random.default_rng(SEED)
    n = SIZE * SIZE
    m = n // 10
    pat = np.zeros((SIZE, SIZE), dtype=np.uint8)
    pat.flat[rng.choice(n, m, replace=False)] = 1

    # Phase 1: relax the initial pattern until no swap improves it.
    for _ in range(10000):
        i = tightest_one(pat)
        pat[i] = 0
        j = biggest_void(pat)
        pat[j] = 1
        if j == i:
            break
    pat_init = pat.copy()

    rank = np.zeros((SIZE, SIZE), dtype=np.int64)

    # Phase 2: remove ones from the tightest cluster. Each removal gets the rank of what remains.
    tmp = pat_init.copy()
    count = int(tmp.sum())
    while count > 0:
        i = tightest_one(tmp)
        tmp[i] = 0
        count -= 1
        rank[i] = count

    # Phase 3: fill zeros into the biggest void. Ranks continue upward from the ones.
    tmp = pat_init.copy()
    count = int(tmp.sum())
    while count < n:
        j = biggest_void(tmp)
        tmp[j] = 1
        rank[j] = count
        count += 1

    assert sorted(rank.flatten().tolist()) == list(range(n)), "ranks must be a permutation"
    return (rank * 256 // n).astype(np.uint8)


def write_header(tile, path):
    lines = [
        "// True blue-noise dither tile, 64x64, generated by tools/make_blue_noise.py. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "namespace ukiyo {",
        "constexpr int kBlueNoiseSize = 64;",
        "constexpr uint8_t kBlueNoise64[kBlueNoiseSize * kBlueNoiseSize] = {",
    ]
    for r in range(SIZE):
        row = ", ".join(str(int(v)) for v in tile[r])
        lines.append("    " + row + ("," if r < SIZE - 1 else ""))
    lines += ["};", "} // namespace ukiyo", ""]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    tile = generate()
    write_header(tile, os.path.join(ROOT, "src", "engine", "blue_noise_64.h"))
    os.makedirs(os.path.join(ROOT, "renders"), exist_ok=True)
    img = np.repeat(np.repeat(tile, 4, axis=0), 4, axis=1)
    Image.fromarray(img, mode="L").save(os.path.join(ROOT, "renders", "blue_noise_64.png"))
    print("wrote src/engine/blue_noise_64.h and renders/blue_noise_64.png")


if __name__ == "__main__":
    main()
